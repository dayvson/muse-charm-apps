#!/usr/bin/env python3
"""Embed text files as C strings: embed_text.py OUT.c IN SYMBOL [IN SYMBOL ...]

    firmware/tools/embed_text.py firmware/luapp_api.c \\
        firmware/luapp_api.md luapp_api_md \\
        firmware/luapp_api_gfx.md luapp_api_gfx_md \\
        firmware/luapp_api_sound.md luapp_api_sound_md
"""
import sys
from pathlib import Path

out, pairs = Path(sys.argv[1]), sys.argv[2:]
assert pairs and len(pairs) % 2 == 0, __doc__
parts = []
for src, sym in zip(pairs[::2], pairs[1::2]):
    src = Path(src)
    text = src.read_text()
    assert all(32 <= ord(c) < 127 or c == "\n" for c in text), f"{src}: ASCII only"
    lines = [l.replace("\\", "\\\\").replace('"', '\\"') + "\\n" for l in text.split("\n")]
    body = "\n".join(f'    "{l}"' for l in lines)
    parts.append(f"/* Generated by firmware/tools/embed_text.py from {src.name}. Do not edit. */\n"
                 f"const char {sym}[] =\n{body};\n")
    print(f"{src.name}: {len(text)} bytes")
out.write_text("\n".join(parts))
